/* Interactive day-in-the-plant figure for the BYD battery project.
   Data: window.BYD_ES_DATA, generated by scripts/byd_es_model.py (synthetic, normalized). */
(function () {
  var root = document.getElementById("byd-es-explorer");
  var D = window.BYD_ES_DATA;
  if (!root || !D || !window.Chart) return;

  var STRATS = {
    "static": "Original: fixed reserve all year",
    "dynamic": "Simplified operator rules",
    "optimal": "Full optimization"
  };
  var TIER_ALPHA = { valley: 0, flat: 0.05, peak: 0.11, critical: 0.2 };
  var TIER_NAME = { valley: "Valley", flat: "Flat", peak: "Peak", critical: "Critical peak" };
  var BLUE = "#2a78d6", ORANGE = "#eb6834", GRAY = "#898781";
  var state = { month: "other", strat: "dynamic" };

  function el(tag, attrs, html) {
    var e = document.createElement(tag);
    for (var k in attrs || {}) e.setAttribute(k, attrs[k]);
    if (html !== undefined) e.innerHTML = html;
    return e;
  }

  function segment(name, options, key) {
    var box = el("div", { "class": "byd-es__seg", role: "group", "aria-label": name });
    Object.keys(options).forEach(function (v) {
      var b = el("button", { type: "button", "data-v": v }, options[v]);
      b.addEventListener("click", function () { state[key] = v; render(); });
      box.appendChild(b);
    });
    return box;
  }

  var months = {};
  Object.keys(D.months).forEach(function (k) { months[k] = D.months[k].label; });
  var controls = el("div", { "class": "byd-es__controls" });
  controls.appendChild(el("span", { "class": "byd-es__label" }, "Month"));
  var mSeg = segment("Month type", months, "month");
  controls.appendChild(mSeg);
  controls.appendChild(el("span", { "class": "byd-es__label" }, "Strategy"));
  var sSeg = segment("Operating strategy", STRATS, "strat");
  controls.appendChild(sSeg);

  var kpis = el("div", { "class": "byd-es__kpis" });
  var K = {};
  [["saving", "Savings vs. original rule"], ["cycles", "Full cycles per day"],
   ["idle", "Charge left at midnight"], ["peak", "Peak demand"]].forEach(function (k) {
    var box = el("div", { "class": "byd-es__kpi" }, "<span>" + k[1] + "</span>");
    K[k[0]] = el("strong", {}, "–");
    box.appendChild(K[k[0]]);
    kpis.appendChild(box);
  });

  var legend1 = el("div", { "class": "byd-es__legend" },
    '<span><i style="background:' + BLUE + '"></i>Battery charging</span>' +
    '<span><i style="background:' + ORANGE + '"></i>Battery discharging</span>' +
    '<span><i class="line" style="border-color:' + GRAY + '"></i>Plant load</span>' +
    "<span>Darker shading = higher price</span>");
  var c1wrap = el("div", { "class": "byd-es__chart" });
  var c1 = el("canvas", { role: "img", "aria-label": "Battery power and plant load over one day, on a background of time-of-use price tiers" });
  c1wrap.appendChild(c1);
  var legend2 = el("div", { "class": "byd-es__legend" },
    '<span><i class="line" style="border-color:' + BLUE + '"></i>Selected strategy</span>' +
    '<span><i class="dash" style="border-color:' + GRAY + '"></i>Original rule</span>' +
    '<span><i class="dash" style="border-color:' + ORANGE + '"></i>Backup reserve</span>');
  var c2wrap = el("div", { "class": "byd-es__chart" });
  var c2 = el("canvas", { role: "img", "aria-label": "Battery state of charge over one day, compared with the original rule and the backup reserve" });
  c2wrap.appendChild(c2);
  var note = el("p", { "class": "byd-es__note" });

  [controls, kpis, legend1, c1wrap, legend2, c2wrap, note].forEach(function (n) { root.appendChild(n); });

  function isDark() { return document.documentElement.getAttribute("data-theme") === "dark"; }
  function ink() { return isDark() ? "#c3c2b7" : "#6b6a65"; }
  function gridColor() { return isDark() ? "rgba(255,255,255,0.12)" : "#e1e0d9"; }

  var labels = D.hours.map(function (h) { return h; });

  var bands = {
    id: "bands",
    beforeDatasetsDraw: function (chart) {
      var a = chart.chartArea, ctx = chart.ctx, tiers = D.months[state.month].tiers;
      var w = (a.right - a.left) / tiers.length, rgb = isDark() ? "255,255,255" : "11,11,11";
      ctx.save();
      tiers.forEach(function (t, i) {
        ctx.fillStyle = "rgba(" + rgb + "," + TIER_ALPHA[t] + ")";
        ctx.fillRect(a.left + i * w, a.top, w + 0.5, a.bottom - a.top);
      });
      if (chart.canvas === c1) {
        ctx.fillStyle = ink();
        ctx.font = "11px sans-serif";
        ctx.textAlign = "center";
        var start = 0;
        for (var i = 1; i <= tiers.length; i++) {
          if (i === tiers.length || tiers[i] !== tiers[start]) {
            if (i - start >= 6) ctx.fillText(TIER_NAME[tiers[start]], a.left + (start + i) / 2 * w, a.top + 12);
            start = i;
          }
        }
      }
      ctx.restore();
    }
  };

  function xAxis() {
    return {
      grid: { display: false },
      ticks: {
        color: ink(), autoSkip: false, maxRotation: 0,
        callback: function (v, i) { return i % 16 === 0 ? (i / 4) + ":00" : ""; }
      }
    };
  }
  function yAxis(title, min, max) {
    return { min: min, max: max, grid: { color: gridColor() },
             ticks: { color: ink(), stepSize: max > 2 ? 25 : 0.5,
                      callback: function (v) { return Math.abs(v % (max > 2 ? 25 : 0.5)) < 1e-9 ? v : ""; } },
             title: { display: true, text: title, color: ink() } };
  }
  function hourTitle(items) {
    var h = items[0].label * 1, hh = Math.floor(h), mm = Math.round((h - hh) * 60);
    return hh + ":" + (mm < 10 ? "0" : "") + mm;
  }

  var powerChart = new Chart(c1, {
    type: "bar",
    data: {
      labels: labels,
      datasets: [
        { type: "line", label: "Plant load", data: D.load, borderColor: GRAY, borderWidth: 1.5, pointRadius: 0, order: 0 },
        { type: "bar", label: "Battery", data: [], backgroundColor: [], barPercentage: 1, categoryPercentage: 0.85, borderRadius: 2, order: 1 }
      ]
    },
    options: {
      responsive: true, maintainAspectRatio: false, animation: { duration: 250 },
      interaction: { mode: "index", intersect: false },
      plugins: {
        legend: { display: false },
        tooltip: { callbacks: {
          title: hourTitle,
          label: function (i) {
            if (i.datasetIndex === 0) return "Plant load " + i.raw.toFixed(2);
            if (Math.abs(i.raw) < 0.005) return "Battery idle";
            return (i.raw > 0 ? "Charging " : "Discharging ") + Math.abs(i.raw).toFixed(2) + " × plant load";
          }
        } }
      },
      scales: { x: xAxis(), y: yAxis("× average plant load", -1.25, 1.5) }
    },
    plugins: [bands]
  });

  var socChart = new Chart(c2, {
    type: "line",
    data: {
      labels: D.hours.concat([24]),
      datasets: [
        { label: "Selected", data: [], borderColor: BLUE, borderWidth: 2, pointRadius: 0 },
        { label: "Original rule", data: [], borderColor: GRAY, borderWidth: 1.5, borderDash: [5, 4], pointRadius: 0 },
        { label: "Reserve", data: [], borderColor: ORANGE, borderWidth: 1, borderDash: [2, 3], pointRadius: 0 }
      ]
    },
    options: {
      responsive: true, maintainAspectRatio: false, animation: { duration: 250 },
      interaction: { mode: "index", intersect: false },
      plugins: {
        legend: { display: false },
        tooltip: {
          filter: function (i) { return i.datasetIndex < 2; },
          callbacks: { title: hourTitle, label: function (i) { return i.dataset.label + ": " + Math.round(i.raw) + "% full"; } }
        }
      },
      scales: { x: xAxis(), y: yAxis("Battery charge (%)", 0, 105) }
    },
    plugins: [bands]
  });

  function pct(v) { return Math.round(v * 100) + "%"; }

  function render() {
    [[mSeg, state.month], [sSeg, state.strat]].forEach(function (p) {
      Array.prototype.forEach.call(p[0].children, function (b) {
        b.setAttribute("aria-pressed", b.getAttribute("data-v") === p[1] ? "true" : "false");
      });
    });
    var m = D.months[state.month], r = m.strategies[state.strat], base = m.strategies["static"];

    powerChart.data.datasets[1].data = r.power;
    powerChart.data.datasets[1].backgroundColor = r.power.map(function (p) { return p >= 0 ? BLUE : ORANGE; });
    socChart.data.datasets[0].label = STRATS[state.strat];
    socChart.data.datasets[0].data = r.soc.map(function (s) { return s * 100; });
    socChart.data.datasets[1].data = state.strat === "static" ? [] : base.soc.map(function (s) { return s * 100; });
    socChart.data.datasets[2].data = r.soc.map(function () { return r.reserve * 100; });

    [powerChart, socChart].forEach(function (c) {
      c.options.scales.x = xAxis();
      var y = c.options.scales.y;
      y.grid.color = gridColor(); y.ticks.color = ink(); y.title.color = ink();
      c.update();
    });

    K.saving.textContent = Math.round(r.saving_index) + (state.strat === "static" ? " (baseline)" : "");
    K.cycles.textContent = r.cycles.toFixed(2);
    K.idle.textContent = pct(r.soc[0]);
    K.peak.textContent = r.peak.toFixed(2) + " ×";
    note.textContent = "Bill change in this illustrative day: " + r.bill_change.total.toFixed(1) +
      "% (energy charges " + r.bill_change.energy.toFixed(1) + "%, demand charge +" +
      r.bill_change.demand.toFixed(1) + "%, per-kWh network charge +" + r.bill_change.volume.toFixed(1) + "%).";
  }

  new MutationObserver(render).observe(document.documentElement, { attributes: true, attributeFilter: ["data-theme"] });
  render();
})();
